# ==========================================================
# GET TEMPLATE NAMES
# ==========================================================

def get_template_names():

    return list(
        DIET_PLAN_TEMPLATES.keys()
    )


# ==========================================================
# GET TEMPLATE
# ==========================================================

def get_diet_plan_template(
    template_name
):

    if template_name not in DIET_PLAN_TEMPLATES:

        raise ValueError(
            "Diet plan template not found."
        )

    return DIET_PLAN_TEMPLATES[
        template_name
    ]


# ==========================================================
# CALCULATE TEMPLATE SUMMARY
# ==========================================================

def get_template_summary(
    template_name
):

    template = get_diet_plan_template(
        template_name
    )

    meals = template["meals"]

    total_calories = sum(
        meal["calories"]
        for meal in meals
    )

    total_protein = sum(
        meal["protein"]
        for meal in meals
    )

    return {
        "total_meals": len(meals),
        "total_calories": total_calories,
        "total_protein": total_protein
    }



# ==========================================================
# APPLY DIET PLAN TEMPLATE
# ==========================================================

def apply_diet_plan_template(
    diet_plan_id,
    template_name
):

    from services.diet_plan_template_service import (
        get_diet_plan_template
    )

    template = get_diet_plan_template(
        template_name
    )

    meals = template["meals"]

    added_meals = []

    for meal in meals:

        meal_id = add_diet_plan_meal(
            diet_plan_id,
            meal["meal_type"],
            meal["meal_time"],
            meal["calories"],
            meal["protein"],
            meal["food_items"],
            meal["rasa"],
            meal["virya"],
            meal["digestion"],
            meal["notes"]
        )

        added_meals.append(meal_id)

    return added_meals