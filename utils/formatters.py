def format_bmi(bmi):
    """
    Format BMI to two decimal places.
    """
    return f"{bmi:.2f}"


def format_weight(weight):
    """
    Format weight with kg.
    """
    return f"{weight:.1f} kg"


def format_height(height):
    """
    Format height with cm.
    """
    return f"{height:.1f} cm"